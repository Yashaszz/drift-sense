"""Render the README's results block from the tracked evidence.

Why this exists
---------------
Two people independently rewrote the README's results table from their own
harness runs. The accuracy figures agreed to the digit; the latency figures
differed by 1.7x, because one was measured on a Mac and the other on a Windows
laptop and neither said so. Whichever rewrite survived the merge conflict would
have decided what went on a slide -- not because it was right, but because it
merged second.

So the table stops being prose. It is generated from ``results/*.csv``, stamped
with the machine from the ``.meta.json`` sidecar, and checked in CI. To change
a number, re-run the harness; the number cannot be edited by hand without the
test failing.

Usage
-----
    uv run python -m scripts.render_results --write   # regenerate the block
    uv run python -m scripts.render_results --check   # CI: fail if stale
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics as st
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import evaluate  # noqa: E402  — needs the path above

BEGIN = "<!-- RESULTS:BEGIN — generated by scripts/render_results.py, do not edit -->"
END = "<!-- RESULTS:END -->"

REPO_ROOT = Path(__file__).resolve().parents[1]
README = REPO_ROOT / "README.md"
FULL = REPO_ROOT / "results" / "full_324.csv"
BASELINE = REPO_ROOT / "results" / "baseline_324.csv"


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _accuracy(rows: list[dict[str, str]]) -> float:
    return sum(int(r["success_1px"]) for r in rows) / len(rows)


def _median_err(rows: list[dict[str, str]]) -> float:
    return st.median(float(r["err_px"]) for r in rows)


def _percentile(values: list[float], fraction: float) -> float:
    ordered = sorted(values)
    return ordered[int(fraction * (len(ordered) - 1))]


def _machine(csv_path: Path) -> str:
    """Describe the machine a CSV was produced on, from its sidecar.

    An unlabelled latency figure is the defect this whole module exists to
    prevent, so a missing sidecar says so out loud rather than quietly omitting
    the attribution.
    """
    sidecar = csv_path.with_suffix(".meta.json")
    if not sidecar.is_file():
        return "**machine unrecorded** — re-run `src.evaluate` to stamp it"
    meta = json.loads(sidecar.read_text(encoding="utf-8"))
    return (
        f"{meta.get('platform', '?')} · Python {meta.get('python', '?')} "
        f"· commit `{meta.get('commit', '?')}`"
    )


def render() -> str:
    """Build the results block from the tracked CSVs."""
    full = _rows(FULL)
    baseline = _rows(BASELINE)

    def split(rows: list[dict[str, str]], stratum: str) -> list[dict[str, str]]:
        return [r for r in rows if r["anchored"] == stratum]

    anchored, unanchored = split(full, "anchored"), split(full, "unanchored")
    base_anchored = split(baseline, "anchored")
    latency = [float(r["elapsed_ms"]) for r in full]

    lines = [
        BEGIN,
        "",
        f"Measured on **{len(full)} stratified synthetic pairs** — 2 architectures x 2 anchor",
        "states x 3 pose conditions x 3 noise strata x 9 seeds — at the 1 px (10 nm)",
        "tolerance, with the SEM physics chain live: real Poisson shot noise and read",
        "noise, varied across three strata.",
        "",
        "| | plain NCC | full pipeline |",
        "|---|---|---|",
        f"| accuracy, **anchored** references (n={len(anchored)}) "
        f"| {_accuracy(base_anchored):.3f} | **{_accuracy(anchored):.3f}** |",
        f"| accuracy, unanchored references (n={len(unanchored)}) "
        f"| {_accuracy(split(baseline, 'unanchored')):.3f} | {_accuracy(unanchored):.3f} |",
        f"| accuracy, all pairs (n={len(full)}) "
        f"| {_accuracy(baseline):.3f} | {_accuracy(full):.3f} |",
        f"| median error, anchored "
        f"| {_median_err(base_anchored):.3f} px | **{_median_err(anchored):.3f} px** |",
        f"| latency, median / p95 | | {st.median(latency):.0f} ms / "
        f"{_percentile(latency, 0.95):.0f} ms |",
        "",
        "Pass rates at the tolerances the problem statement asks for (5, 4, 2 and 1 px):",
        "",
        "| tolerance | plain NCC (all / anchored) | full pipeline (all / anchored) |",
        "|---|---|---|",
        *[
            f"| ≤ {tol:.0f} px | {b_all:.3f} / {b_anch:.3f} | {f_all:.3f} / **{f_anch:.3f}** |"
            for (tol, f_all, f_anch), (_, b_all, b_anch) in zip(
                reversed(evaluate.pass_rates(full)),
                reversed(evaluate.pass_rates(baseline)),
                strict=True,
            )
        ],
        "",
        f"Latency is a property of the machine, not of the code: {_machine(FULL)}. "
        "The same 324 pairs on a different machine will report a different figure "
        "and the same accuracy.",
        "",
        "Regenerate with `uv run python -m src.evaluate --data dataset --out "
        "results/full_324.csv`, then `uv run python -m scripts.render_results --write`.",
        "",
        END,
    ]
    return "\n".join(lines)


def _splice(readme: str, block: str) -> str:
    start, end = readme.index(BEGIN), readme.index(END) + len(END)
    return readme[:start] + block + readme[end:]


def main() -> int:
    """Regenerate the README block, or verify it against the CSVs."""
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the block in place")
    group.add_argument("--check", action="store_true", help="exit 1 if the block is stale")
    args = parser.parse_args()

    readme = README.read_text(encoding="utf-8")
    if BEGIN not in readme or END not in readme:
        print(f"{README} has no RESULTS block; add the markers first", file=sys.stderr)
        return 2

    updated = _splice(readme, render())
    if args.write:
        README.write_text(updated, encoding="utf-8")
        print(f"Wrote the results block to {README}")
        return 0

    if updated != readme:
        print(
            "README results block is stale — it does not match results/*.csv.\n"
            "Run: uv run python -m scripts.render_results --write",
            file=sys.stderr,
        )
        return 1
    print("README results block matches the tracked CSVs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
