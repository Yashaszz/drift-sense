@pytest.mark.parametrize("noise", [0.02, 0.05, 0.1])
def test_survives_moderate_noise(noise):
    dy, dx = 0.35, -0.4
    template, search = make_case(dy, dx, noise=noise)
    refinement = matcher.refine_subpixel_detailed(template, search, PEAK)

    assert np.hypot(dx - refinement.dx, dy - refinement.dy) < 0.25


def test_registration_error_rises_with_noise():
    """The reported error must be informative, not decorative."""
    errors = []
    for noise in (0.0, 0.05, 0.2, 0.5):
        template, search = make_case(0.2, 0.2, noise=noise)
        errors.append(matcher.refine_subpixel_detailed(template, search, PEAK).error)

    assert errors == sorted(errors)


def test_wild_offsets_are_rejected_rather_than_applied():
    """A refinement larger than a pixel means the estimator latched onto noise.

    Applying it would turn a correct integer answer into a badly wrong sub-pixel
    one, so the offset is discarded and the result marked.
    """
    template = band_limited_field()[TEMPLATE_SLICE].copy()
    search = np.random.default_rng(9).normal(0, 1, (256, 256)).astype(np.float32)

    refinement = matcher.refine_subpixel_detailed(template, search, PEAK)
    assert abs(refinement.dx) <= 1.0
    assert abs(refinement.dy) <= 1.0


def test_constant_template_is_rejected():
    template = np.full((64, 64), 5.0, dtype=np.float32)
    search = band_limited_field()
    refinement = matcher.refine_subpixel_detailed(template, search, PEAK)
    assert refinement.method == "rejected"
    assert refinement.dx == 0.0
    assert refinement.dy == 0.0


def test_out_of_bounds_peak_is_rejected():
    template, search = make_case(0.0, 0.0)
    far = Peak(col=search.shape[1] - 2, row=search.shape[0] - 2, score=1.0)
    refinement = matcher.refine_subpixel_detailed(template, search, far)
    assert refinement.method == "rejected"


def test_is_deterministic():
    template, search = make_case(0.3, -0.2)
    first = matcher.refine_subpixel_detailed(template, search, PEAK)
    second = matcher.refine_subpixel_detailed(template, search, PEAK)
    assert (first.dx, first.dy) == (second.dx, second.dy)


def test_does_not_mutate_its_inputs():
    template, search = make_case(0.3, -0.2)
    before_template, before_search = template.copy(), search.copy()
    matcher.refine_subpixel_detailed(template, search, PEAK)
    np.testing.assert_array_equal(template, before_template)
    np.testing.assert_array_equal(search, before_search)


