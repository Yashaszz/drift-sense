def test_localize_reports_subpixel_diagnostics(two_scale_pair):
    from src.localize import localize

    reference, search, _ = two_scale_pair
    result = localize(search, reference, mode="fast")

    assert result.diagnostics.subpixel_method == "phase_cross_correlation"
    assert np.isfinite(result.diagnostics.subpixel_error)
    assert 0.0 <= result.diagnostics.subpixel_error <= 1.0


def test_localize_produces_non_integer_coordinates(two_scale_pair):
    """Sub-pixel output must actually be sub-pixel, not silently rounded."""
    from src.localize import localize

    reference, search, _ = two_scale_pair
    shifted = fourier_shift(search, 0.3, -0.4)
    result = localize(shifted, reference, mode="fast")

    assert (result.x % 1.0, result.y % 1.0) != (0.5, 0.5)
