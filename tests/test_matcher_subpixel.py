@pytest.mark.parametrize("dy, dx", [(0.0, 0.3), (0.3, 0.0), (-0.25, 0.4)])
def test_surface_upsampling_also_recovers_the_shift(dy, dx):
    template, search = make_case(dy, dx)
    surface = matcher.zncc_surface(template, search)
    offset_x, offset_y = matcher.refine_subpixel(surface, PEAK)

    assert offset_x == pytest.approx(dx, abs=0.15)
    assert offset_y == pytest.approx(dy, abs=0.15)


def test_both_routines_are_far_better_than_no_refinement():
    """Both are accurate; which is *more* accurate depends on the content.

    On band-limited noise the phase-correlation routine wins. On a strongly
    periodic field the surface-upsampling routine wins, because a lattice
    produces an unusually smooth, well-sampled correlation peak that interpolates
    very cleanly — the benchmark measures 0.004 px against 0.013 px there.

    So the assertion here is the one that actually holds across content: both
    routines cut the residual substantially against taking the integer peak.
    Declaring either universally superior would be over-claiming from one
    synthetic distribution, and the choice should be revisited on R1's realistic
    data rather than settled here.

    Measured on this fixture: integer 0.403 px, phase correlation 0.010 px
    (41x better), surface upsampling 0.087 px (4.6x better). The thresholds
    below are deliberately looser than those figures so the test tracks a real
    regression rather than fixture noise.
    """
    rng = np.random.default_rng(4)
    integer, primary, fallback = [], [], []
    for _ in range(20):
        dy, dx = rng.uniform(-0.5, 0.5, 2)
        template, search = make_case(dy, dx)
        surface = matcher.zncc_surface(template, search)

        pcc = matcher.refine_subpixel_detailed(template, search, PEAK)
        sx, sy = matcher.refine_subpixel(surface, PEAK)

        integer.append(np.hypot(dx, dy))
        primary.append(np.hypot(dx - pcc.dx, dy - pcc.dy))
        fallback.append(np.hypot(dx - sx, dy - sy))

    assert float(np.median(primary)) < float(np.median(integer)) / 10
    assert float(np.median(fallback)) < float(np.median(integer)) / 3


def test_falls_back_when_the_primary_is_rejected():
    template = np.full((64, 64), 5.0, dtype=np.float32)
    search = band_limited_field()
    surface = np.zeros((100, 100), dtype=np.float32)
    surface[60, 90] = 1.0

    refinement = matcher.refine_subpixel_detailed(template, search, PEAK, surface=surface)
    assert refinement.method in {"surface_upsampling", "rejected"}


def test_upsampled_patch_reproduces_its_samples():
    """Sanity check on the interpolator: at integer offsets it must be exact."""
    patch = np.array(
        [[0.1, 0.2, 0.1], [0.2, 1.0, 0.3], [0.1, 0.3, 0.2]],
        dtype=np.float32,
    )
    values, offsets = matcher._upsampled_patch(patch, upsample=1, span=1.0)
    np.testing.assert_allclose(values, patch, atol=1e-6)
    np.testing.assert_allclose(offsets, [-1.0, 0.0, 1.0], atol=1e-12)


