@pytest.mark.parametrize("upsample", [0, -1])
def test_all_entry_points_reject_invalid_upsample(upsample):
    template, search = make_case(0.0, 0.0)
    surface = np.zeros((100, 100), dtype=np.float32)

    with pytest.raises(ValueError, match="upsample"):
        matcher.refine_subpixel(surface, PEAK, upsample=upsample)
    with pytest.raises(ValueError, match="upsample"):
        matcher.refine_subpixel_crop(template, search, PEAK, upsample=upsample)
    with pytest.raises(ValueError, match="upsample"):
        matcher.refine_subpixel_detailed(template, search, PEAK, upsample=upsample)


def test_tuple_entry_points_agree_with_the_detailed_one():
    template, search = make_case(0.3, -0.2)
    detailed = matcher.refine_subpixel_detailed(template, search, PEAK)
    assert matcher.refine_subpixel_crop(template, search, PEAK) == (detailed.dx, detailed.dy)


def test_default_upsample_comes_from_config():
    template, search = make_case(0.25, 0.25)
    explicit = matcher.refine_subpixel_crop(
        template, search, PEAK, upsample=config.DEFAULT_UPSAMPLE
    )
    assert matcher.refine_subpixel_crop(template, search, PEAK) == explicit


